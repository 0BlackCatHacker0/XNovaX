# === DISPATCH TASK (canonical) ===
A('')
A('// === CANONICAL DISPATCH ===')
A('async function _hiveDispatch(prompt,modelList){')
A('  if(!prompt)return;')
A('  _hiveMetrics.sent++;')
A('  var models=modelList||[];')
A('  if(models.length===0){')
A('    var fast=_hiveModels.filter(function(m){return m.cat==="fast";})[0];')
A('    var reason=_hiveModels.filter(function(m){return m.cat==="reasoning";})[0];')
A('    if(fast)models.push(fast.name);')
A('    if(reason)models.push(reason.name);')
A('    if(models.length===0&&_hiveModels.length>0)models.push(_hiveModels[0].name);')
A('  }')
A('  var taskId="T"+Date.now();')
A('  var task={id:taskId,prompt:prompt,models:models,status:"running",ts:Date.now(),results:[]};')
A('  _hiveTasks.unshift(task);')
A('  _hiveRenderTasks();')
A('  _hiveLog("Dispatching to "+models.length+" models: "+models.join(", "));')
A('  try{')
A('    var t0=performance.now();')
A('    var r=await fetch(API+"/api/hive",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({prompt:prompt,models:models})});')
A('    var d=await r.json();')
A('    var elapsed=performance.now()-t0;')
A('    task.status=d.ok?"done":"error";')
A('    task.results=d.results||[];')
A('    task.elapsed=Math.round(elapsed);')
A('    if(d.ok){_hiveMetrics.ok++;_hiveMetrics.totalMs+=elapsed;}')
A('    else _hiveMetrics.fail++;')
A('    _hiveRenderGrid(task);')
A('    _hiveRenderTasks();')
A('    _hiveLog("Hive done "+Math.round(elapsed)+"ms - "+task.results.length+" responses");')
A('  }catch(e){')
A('    task.status="error";task.error=e.message;_hiveMetrics.fail++;')
A('    _hiveRenderTasks();_hiveLog("Dispatch error: "+e.message);')
A('  }')
A('}')
A('')

