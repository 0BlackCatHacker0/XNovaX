A('')
A('var catColors={code:"#00ff88",vision:"#ff44ff",fast:"#ffaa00",chat:"#44aaff",reasoning:"#ff6644",general:"#888"};')
A('')

# === FETCH MODELS ===
A('async function _hiveFetch(){')
A('  try{')
A('    var r=await fetch(API+"/api/ollama/models");')
A('    var d=await r.json();')
A('    if(!d.ok)return[];')
A('    _hiveModels=(d.models||[]).map(function(m){')
