A('  _hiveModels.forEach(function(m){')
A('    if(!cats[m.cat])cats[m.cat]=[];')
A('    cats[m.cat].push(m);')
A('  });')
A('  var html="";')
A('  var keys=Object.keys(cats).sort();')
A('  keys.forEach(function(k){')
